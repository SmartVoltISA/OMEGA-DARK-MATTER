import numpy as np
from scipy.optimize import minimize


def relax_kink(N, k=1.0):
    x = np.arange(N, dtype=float)
    q0 = np.tanh((x - (N - 1) / 2) / np.sqrt(2.0 * k))
    def energy(z):
        q = np.r_[-1.0, z, 1.0]
        return 0.5 * k * np.sum(np.diff(q) ** 2) + 0.25 * np.sum((q*q - 1.0) ** 2)
    res = minimize(energy, q0[1:-1], method='L-BFGS-B', options={'maxiter': 3000, 'ftol': 1e-14})
    return np.r_[-1.0, res.x, 1.0]


def gradV(q, k):
    g = np.zeros_like(q)
    g[1:-1] = k * (2*q[1:-1] - q[:-2] - q[2:]) + q[1:-1] * (q[1:-1]**2 - 1.0)
    return g


def center(q):
    # Linear interpolation of the q=0 crossing.
    s = np.sign(q)
    idx = np.where(s[:-1] * s[1:] <= 0)[0]
    if len(idx) == 0:
        return np.nan
    i = idx[len(idx)//2]
    den = q[i+1] - q[i]
    return float(i - q[i] / den) if den != 0 else float(i)


def run(N, k, h, sign, dt=0.02, steps=2500):
    q = relax_kink(N, k)
    x = np.arange(N, dtype=float)
    qx = np.gradient(q, x)
    v = np.zeros_like(q)
    # Uniform bias term V_ext = -h * sum(q), hence qddot contains +h.
    # For a translated kink, d(sum q)/dX ~= -2, so the generalized force
    # magnitude is approximately 2*h, independently calibrated from the field bias.
    a0 = -gradV(q, k) + sign * h
    a = a0.copy()
    centers = []
    times = []
    for step in range(steps):
        if step % 5 == 0:
            centers.append(center(q)); times.append(step * dt)
        q[1:-1] += dt * v[1:-1] + 0.5 * dt*dt * a[1:-1]
        a_new = -gradV(q, k) + sign * h
        v[1:-1] += 0.5 * dt * (a[1:-1] + a_new[1:-1])
        a = a_new
    t = np.asarray(times)
    X = np.asarray(centers)
    good = np.isfinite(X)
    t, X = t[good], X[good]
    # Early response window: avoid boundary interaction.
    mask = (t >= 4.0) & (t <= 18.0)
    coef = np.polyfit(t[mask], X[mask], 2)
    acc = 2.0 * coef[0]
    return acc, 2.0 * h / abs(acc), coef[2], coef[1]


